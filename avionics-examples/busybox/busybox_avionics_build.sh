    echo "MIL-STD-1553 Support: $ENABLE_MILSTD1553"
    echo ""
    echo "Generated Files:"
    ls -la "$BUILD_DIR/images/"
    echo ""
    echo "Root Filesystem Size:"
    du -sh "$BUILD_DIR/rootfs"
    echo ""
    print_success "Avionics BusyBox Linux build completed successfully!"
}

