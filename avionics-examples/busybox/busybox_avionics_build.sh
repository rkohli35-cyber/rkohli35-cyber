# Build BusyBox
build_busybox() {
    print_info "Building BusyBox..."
    
    cd "$BUILD_DIR/busybox-$BUSYBOX_VERSION"
    
    # Build with custom configuration
    make -j$(nproc)
    
    # Install to staging directory
    make CONFIG_PREFIX="../rootfs" install
    
    cd ../..
    print_success "BusyBox build completed"
}

# Create root filesystem structure
create_rootfs() {
    print_info "Creating root filesystem structure..."
    
    cd "$BUILD_DIR/rootfs"
    
    # Create essential directories
    mkdir -p {dev,proc,sys,tmp,var,run,mnt,opt}
    mkdir -p {etc,home,root,usr/{bin,sbin,lib}}
    mkdir -p var/{log,lib,tmp,run,spool}
    mkdir -p etc/{init.d,rc.d,network}
    
    # Create device nodes
    mknod dev/null c 1 3
    mknod dev/zero c 1 5
    mknod dev/console c 5 1
    mknod dev/tty c 5 0
    mknod dev/ttyS0 c 4 64
    mknod dev/random c 1 8
    mknod dev/urandom c 1 9
    
    # Set permissions
    chmod 666 dev/{null,zero,random,urandom}
    chmod 600 dev/console
    chmod 666 dev/tty*
    
    # Create mount points for avionics hardware
    mkdir -p {mnt/{can,arinc,milstd},dev/{can,arinc,milstd}}
    
    cd ../..
    print_success "Root filesystem structure created"
}

# Create avionics-specific configuration files
create_avionics_configs() {
    print_info "Creating avionics-specific configuration files..."
    
    cd "$BUILD_DIR/rootfs"
    
    # Create inittab for avionics
    cat > etc/inittab << 'EOF'
# Avionics System Init Configuration
::sysinit:/etc/init.d/rcS
::respawn:/sbin/getty -L ttyS0 115200 vt100
::restart:/sbin/init
::ctrlaltdel:/sbin/reboot
::shutdown:/etc/init.d/rcK
null::sysinit:/bin/mount -t proc proc /proc
null::sysinit:/bin/mount -t sysfs sysfs /sys
null::sysinit:/bin/mount -t tmpfs tmpfs /tmp
null::sysinit:/sbin/mdev -s

# Avionics startup
::once:/etc/init.d/avionics-startup
::respawn:/usr/bin/avionics-monitor
EOF

    # Create startup script
    cat > etc/init.d/rcS << 'EOF'
#!/bin/sh
# Avionics System Startup Script

echo "Starting Avionics Linux System..."

# Mount filesystems
/bin/mount -a

# Configure hostname
echo "avionics-system" > /proc/sys/kernel/hostname

# Configure real-time kernel
if [ "$ENABLE_REAL_TIME" = "true" ]; then
    echo "Configuring real-time kernel parameters..."
    echo 0 > /proc/sys/kernel/hung_task_timeout_secs
    echo 1000000 > /proc/sys/kernel/sched_rt_runtime_us
    echo 1000000 > /proc/sys/kernel/sched_rt_period_us
fi

# Load avionics kernel modules
echo "Loading avionics kernel modules..."
if [ "$ENABLE_CAN_SUPPORT" = "true" ]; then
    modprobe can
    modprobe can-dev
    modprobe can-raw
fi

if [ "$ENABLE_ARINC429" = "true" ]; then
    modprobe arinc429 || echo "ARINC 429 module not available"
fi

if [ "$ENABLE_MILSTD1553" = "true" ]; then
    modprobe mil1553 || echo "MIL-STD-1553 module not available"
fi

# Configure network interfaces
echo "Configuring network interfaces..."
ifconfig lo 127.0.0.1 up

# Start system services
echo "Starting system services..."
/sbin/syslogd
/sbin/klogd

# Configure watchdog
if [ "$ENABLE_WATCHDOG" = "true" ]; then
    echo "Starting hardware watchdog..."
    /sbin/watchdog /dev/watchdog
fi

# Run avionics hardware tests
echo "Running avionics hardware self-tests..."
/usr/bin/avionics-selftest

echo "Avionics system startup completed."
EOF
    chmod +x etc/init.d/rcS

    # Create avionics startup script
    cat > etc/init.d/avionics-startup << 'EOF'
#!/bin/sh
# Avionics Application Startup

echo "Initializing avionics applications..."

# Set CPU affinity for real-time tasks
echo "Configuring CPU affinity..."
echo 2 > /sys/devices/system/cpu/cpu0/cpufreq/scaling_governor
echo performance > /sys/devices/system/cpu/cpu0/cpufreq/scaling_governor

# Configure memory locking
echo "Configuring memory management..."
echo 1 > /proc/sys/vm/drop_caches
ulimit -l unlimited

# Start avionics applications
echo "Starting avionics applications..."
/usr/bin/avionics-display &
/usr/bin/avionics-nav &
/usr/bin/avionics-comm &

echo "Avionics applications started."
EOF
    chmod +x etc/init.d/avionics-startup

    # Create shutdown script
    cat > etc/init.d/rcK << 'EOF'
#!/bin/sh
# Avionics System Shutdown Script

echo "Shutting down avionics system..."

# Stop avionics applications gracefully
echo "Stopping avionics applications..."
killall avionics-display
killall avionics-nav
killall avionics-comm

# Stop system services
echo "Stopping system services..."
killall watchdog
killall klogd
killall syslogd

# Unmount filesystems
echo "Unmounting filesystems..."
/bin/umount -a -r

echo "Avionics system shutdown completed."
EOF
    chmod +x etc/init.d/rcK

    # Create fstab
    cat > etc/fstab << 'EOF'
# Avionics System File System Table
proc            /proc           proc    defaults        0       0
sysfs           /sys            sysfs   defaults        0       0
tmpfs           /tmp            tmpfs   defaults        0       0
tmpfs           /var/run        tmpfs   defaults        0       0
tmpfs           /var/log        tmpfs   defaults        0       0
/dev/mmcblk0p1  /boot           vfat    ro              0       2
/dev/mmcblk0p2  /               ext4    defaults        0       1
EOF

    # Create passwd file
    cat > etc/passwd << 'EOF'
root:x:0:0:root:/root:/bin/sh
avionics:x:1000:1000:Avionics User:/home/avionics:/bin/sh
EOF

    # Create group file
    cat > etc/group << 'EOF'
root:x:0:
avionics:x:1000:
EOF

    # Create shadow file
    cat > etc/shadow << 'EOF'
root::0:0:99999:7:::
avionics::0:0:99999:7:::
EOF
    chmod 600 etc/shadow

    # Create network interfaces configuration
    cat > etc/network/interfaces << 'EOF'
# Avionics Network Configuration
auto lo
iface lo inet loopback

auto eth0
iface eth0 inet static
    address 192.168.1.100
    netmask 255.255.255.0
    gateway 192.168.1.1
    dns-nameservers 8.8.8.8 8.8.4.4
EOF

    # Create syslog configuration
    cat > etc/syslog.conf << 'EOF'
# Avionics System Log Configuration
*.*                     /var/log/messages
kern.*                  /var/log/kernel.log
daemon.*                /var/log/daemon.log
mail.*                  /var/log/mail.log
user.*                  /var/log/user.log
*.emerg                 *
EOF

    cd ../..
    print_success "Avionics configuration files created"
}

# Create initramfs
create_initramfs() {
    print_info "Creating initramfs..."
    
    cd "$BUILD_DIR"
    
    # Copy rootfs to initramfs
    cp -a rootfs/* initramfs/
    
    # Create initramfs archive
    cd initramfs
    find . | cpio -o -H newc | gzip > ../images/initramfs.cpio.gz
    cd ..
    
    # Calculate size
    ls -lh images/initramfs.cpio.gz
    
    cd ..
    print_success "Initramfs created"
}

